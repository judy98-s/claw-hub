package payout

// Bank는 송금 대상 은행이다.
type Bank struct {
	// Code는 금융결제원 기관코드다. 저장과 API 주고받기에 쓴다.
	Code string `json:"code"`
	// Name은 손님과 사장님 화면에 보이는 정식 명칭이다.
	Name string `json:"name"`
	// Short는 송금 앱 딥링크가 받는 짧은 은행명이다.
	//
	// 토스 딥링크는 기관코드(004)도 정식명("국민은행")도 아닌 "국민" 형태를
	// 받는다. 이건 토스가 공식 문서로 제공하는 규격이 아니라 커뮤니티가
	// 관찰해 정리한 값이라, 아래 값들은 실기기에서 확인이 필요하다.
	// 틀린 값이 있으면 PAYOUT_DEEPLINK_TEMPLATES 수정으로는 못 고치므로
	// 여기를 고쳐야 한다.
	Short string `json:"-"`
}

// banks는 손님이 고를 수 있는 은행이다.
// 인터넷은행을 앞에 뒀다 — 인형뽑기 주 이용층이 가장 많이 쓴다.
