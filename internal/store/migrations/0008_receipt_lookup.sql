-- 접수번호(UUID 앞 8자)로 공개 상태를 조회하기 위한 인덱스.
--
-- 손님은 UUID 전체를 모른다. 스티커를 찍고 접수하면 받는 것은 대문자 8자
-- 뿐이다. 그걸로 찾으려면 id 를 문자열로 바꿔 접두사 비교를 해야 하는데,
-- 그건 일반 인덱스로는 쓰이지 않는다. 표현식 인덱스를 둔다.
--
-- machine_id 를 함께 넣는 이유는 성능이 아니라 정확성이다. 접수번호는
-- 32비트라서 7만 건쯤에서 충돌 확률이 50% 를 넘는다. 조회를 기계 단위로
-- 좁히면 충돌이 사실상 사라지고, 다른 매장 건을 긁는 것도 막힌다.
CREATE INDEX claims_receipt_idx
    ON claims (machine_id, substr(replace(id::text, '-', ''), 1, 8));
